/**
 * Refreshes the wizard's vendored copy of the panel's template library.
 *
 * The wizard shows the same templates the panel does, but its build must never
 * depend on the network — the machine that builds it often cannot reach much.
 * So the list is committed, and this script updates it on demand from the
 * panel's latest release.
 *
 *   npm run sync-templates            latest release
 *   npm run sync-templates -- <path>  a local dist/templates.json
 */
import { readFileSync, writeFileSync } from 'fs';
import { dirname as pathDirname, join } from 'path';
import { fileURLToPath } from 'url';

const __dirname = pathDirname(fileURLToPath(import.meta.url));
const OUT = join(__dirname, '../web/assets/templates.js');
const RELEASE = 'https://github.com/rexteamiran/ZAG-Panel/releases/latest/download/templates.json';

const localPath = process.argv[2];

async function load() {
    if (localPath) {
        console.log(`Reading ${localPath}`);
        return JSON.parse(readFileSync(localPath, 'utf8'));
    }

    console.log(`Downloading ${RELEASE}`);
    const res = await fetch(RELEASE);
    if (!res.ok) {
        throw new Error(
            `Could not download the template list: HTTP ${res.status}. ` +
            'Run the panel\'s "Build and Release" workflow first, or pass a local dist/templates.json.'
        );
    }

    return await res.json();
}

const payload = await load();

if (!Array.isArray(payload?.templates) || !payload.templates.length) {
    throw new Error('That file carries no templates.');
}

const banner = `/* Generated by scripts/sync-templates.mjs — do not edit by hand.
   Source: ZAG-Panel ${payload.version ?? 'unknown'} */\n`;

writeFileSync(OUT, `${banner}window.ZAG_TEMPLATES = ${JSON.stringify(payload.templates, null, 2)};\n`, 'utf8');

console.log(`✔ ${payload.templates.length} templates written to web/assets/templates.js`);
console.log('  Commit it so the deployed wizard carries the same list.');
